    private void carregarBox() {
        List<Consulta> consultas = consultadao.ler();
        consultaJComboBox.removeAllItems();
        for (Consulta consulta : consultas) {
            consultaJComboBox.addItem(consulta);
        }
    }

    public void lerTabela() {
        DefaultTableModel modeloPadrao = (DefaultTableModel) medicamentoJTable.getModel();
        modeloPadrao.setNumRows(0);

        for (Medicamento medicamento : medicamentodao.ler()) {
            modeloPadrao.addRow(new Object[]{
                medicamento.getId(), medicamento.getIdConsulta(), medicamento.getNome(), medicamento.getFormato(),
                medicamento.getFabricante(), medicamento.getDataVencimento()
            });
        }
    }

