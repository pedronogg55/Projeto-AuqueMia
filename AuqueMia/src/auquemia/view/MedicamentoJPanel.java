    private void atualizarJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_atualizarJButtonActionPerformed
        try {
            Consulta consulta = new Consulta();
            if (medicamentoJTable.getSelectedRow() != -1) {

                medicamento.setNome(nomeJTextField.getText());
                medicamento.setFormato(formatoJTextField.getText());
                medicamento.setFabricante(fabricanteJTextField.getText());
                medicamento.setDataVencimento(dataValidadeJTextField.getText());
                consulta = (Consulta) consultaJComboBox.getSelectedItem();
                medicamento.setIdConsulta(consulta.getId());
                medicamento.setId((int) medicamentoJTable.getValueAt(medicamentoJTable.getSelectedRow(), 0));
                medicamentodao.atualizar(medicamento);
                JOptionPane.showMessageDialog(null, "Registro do medicamento modificado com sucesso.");
                limparJButtonActionPerformed(evt);
                lerTabela();
            } else {
                JOptionPane.showMessageDialog(null, "Selecione um medicamento.");
            }
        } catch (RuntimeException re) {
            JOptionPane.showMessageDialog(null, re.getMessage());
            re.printStackTrace();
        }
    }//GEN-LAST:event_atualizarJButtonActionPerformed

    private void salvarJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_salvarJButtonActionPerformed
        try {
            Consulta consulta = new Consulta();
            medicamento.setNome(nomeJTextField.getText());
            medicamento.setFormato(formatoJTextField.getText());
            medicamento.setFabricante(fabricanteJTextField.getText());
            medicamento.setDataVencimento(dataValidadeJTextField.getText());
            consulta = (Consulta) consultaJComboBox.getSelectedItem();
            medicamento.setIdConsulta(consulta.getId());
            medicamentodao.criar(medicamento);
            JOptionPane.showMessageDialog(null, "Um registro de medicamento foi salvo com sucesso.");
            limparJButtonActionPerformed(evt);
            lerTabela();
        } catch (RuntimeException re) {
            JOptionPane.showMessageDialog(null, re.getMessage());
            re.printStackTrace();
        }
    }//GEN-LAST:event_salvarJButtonActionPerformed

    private void limparJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_limparJButtonActionPerformed
        nomeJTextField.setText("");
        formatoJTextField.setText("");
        fabricanteJTextField.setText("");
        dataValidadeJTextField.setText("");
    }//GEN-LAST:event_limparJButtonActionPerformed

    private void excluirJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_excluirJButtonActionPerformed
        int id = (int) medicamentoJTable.getValueAt(medicamentoJTable.getSelectedRow(), 0);
        if (medicamentoJTable.getSelectedRow() != -1) {
            medicamentodao.deletar(id);
            JOptionPane.showMessageDialog(null, "Registro do medicamento removido.");
            lerTabela();
        } else {
            JOptionPane.showMessageDialog(null, "Selecione um medicamento para remover.");
        }
    }//GEN-LAST:event_excluirJButtonActionPerformed

