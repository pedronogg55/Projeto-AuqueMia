    private void atualizarJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_atualizarJButtonActionPerformed
        try {
            Tutor tutor = new Tutor();
            if (animalJTable.getSelectedRow() != -1) {
                animal.setNome(nomeJTextField.getText());
                animal.setEspecie(especieJTextField.getText());
                animal.setRaca(racaJTextField.getText());
                animal.setIdade(idadeJTextField.getText());
                tutor = (Tutor) tutorJComboBox.getSelectedItem();
                animal.setIdTutor(tutor.getId());
                animal.setId((int) animalJTable.getValueAt(animalJTable.getSelectedRow(), 0));
                animaldao.atualizar(animal);
                JOptionPane.showMessageDialog(null, "Registro do animal modificado com sucesso.");
                limparJButtonActionPerformed(evt);
                lerTabela();
            } else {
                JOptionPane.showMessageDialog(null, "Selecione um registro.");
            }
        } catch (RuntimeException re) {
            JOptionPane.showMessageDialog(null, re.getMessage());
            re.printStackTrace();
        }
    }//GEN-LAST:event_atualizarJButtonActionPerformed

