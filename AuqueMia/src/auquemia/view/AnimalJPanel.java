    private void carregarBox() {
        List<Tutor> tutores = tutordao.ler();
        tutorJComboBox.removeAllItems();
        for (Tutor tutor : tutores) {
            tutorJComboBox.addItem(tutor);
        }
    }

    public void lerTabela() {
        DefaultTableModel modeloPadrao = (DefaultTableModel) animalJTable.getModel();
        modeloPadrao.setNumRows(0);

        for (Animal animal : animaldao.ler()) {
            modeloPadrao.addRow(new Object[]{
                animal.getId(), animal.getIdTutor(), animal.getNome(), animal.getEspecie(), animal.getRaca(), animal.getIdade()
            });
        }
    }

