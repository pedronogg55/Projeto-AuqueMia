    private void salvarJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_salvarJButtonActionPerformed
         try {
            Tutor tutor = new Tutor();

            animal.setNome(nomeJTextField.getText());
            animal.setEspecie(especieJTextField.getText());
            animal.setRaca(racaJTextField.getText());
            animal.setIdade(idadeJTextField.getText());
            tutor = (Tutor) tutorJComboBox.getSelectedItem();
            animal.setIdTutor(tutor.getId());
            animaldao.criar(animal);
            JOptionPane.showMessageDialog(null, "Um registro do animal foi salvo com sucesso.");
            limparJButtonActionPerformed(evt);
            lerTabela();
        } catch (RuntimeException re) {
            JOptionPane.showMessageDialog(null, re.getMessage());
            re.printStackTrace();
        }
    }//GEN-LAST:event_salvarJButtonActionPerformed

    private void excluirJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_excluirJButtonActionPerformed
        int id = (int) animalJTable.getValueAt(animalJTable.getSelectedRow(), 0);
        if (animalJTable.getSelectedRow() != -1) {
            animaldao.deletar(id);
            JOptionPane.showMessageDialog(null, "Registro do animal removido.");
            lerTabela();
        } else {
            JOptionPane.showMessageDialog(null, "Selecione um animal para remover.");
        }
    }//GEN-LAST:event_excluirJButtonActionPerformed

