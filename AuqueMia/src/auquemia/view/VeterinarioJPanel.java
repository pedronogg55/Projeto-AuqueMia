    private void salvarJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_salvarJButtonActionPerformed
        try {
            veterinario.setNome(nomeJTextField.getText());
            veterinario.setCpf(cpfJTextField.getText());
            veterinario.setTelefone(telefoneJTextField.getText());
            veterinario.setEspecialidade(especialidadeJTextField.getText());
            veterinario.setCrmv(crmvJTextField.getText());

            String horas = horasTrabalhadasJTextField.getText();
            if (!horas.isBlank()) {
                veterinario.setHorasTrabalhadas(Integer.parseInt(horasTrabalhadasJTextField.getText()));
                veterinariodao.criar(veterinario);
                JOptionPane.showMessageDialog(null, "Um registro do veterinario foi salvo com sucesso.");
                limparJButtonActionPerformed(evt);
                lerTabela();
            } else {
                JOptionPane.showMessageDialog(null, "Preencha quantas horas de trabalho o veterinário possui.");
            }
        } catch (RuntimeException re) {
            JOptionPane.showMessageDialog(null, re.getMessage());
            re.printStackTrace();
        }
    }//GEN-LAST:event_salvarJButtonActionPerformed

    private void atualizarJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_atualizarJButtonActionPerformed
        try {
            if (veterinarioJTable.getSelectedRow() != -1) {
                veterinario.setNome(nomeJTextField.getText());
                veterinario.setCpf(cpfJTextField.getText());
                veterinario.setTelefone(telefoneJTextField.getText());
                veterinario.setEspecialidade(especialidadeJTextField.getText());
                veterinario.setCrmv(crmvJTextField.getText());

                String horas = horasTrabalhadasJTextField.getText();
                if (!horas.isBlank()) {
                    veterinario.setHorasTrabalhadas(Integer.parseInt(horasTrabalhadasJTextField.getText()));
                    veterinario.setId((int) veterinarioJTable.getValueAt(veterinarioJTable.getSelectedRow(), 0));
                    veterinariodao.atualizar(veterinario);
                    JOptionPane.showMessageDialog(null, "Registro do veterinario modificado com sucesso.");
                    limparJButtonActionPerformed(evt);
                    lerTabela();
                } else {
                    JOptionPane.showMessageDialog(null, "Preencha quantas horas de trabalho o veterinário possui.");
                }
            } else {
                JOptionPane.showMessageDialog(null, "Selecione um registro.");
            }
        } catch (RuntimeException re) {
            JOptionPane.showMessageDialog(null, re.getMessage());
            re.printStackTrace();
        }
    }//GEN-LAST:event_atualizarJButtonActionPerformed

    private void limparJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_limparJButtonActionPerformed
        nomeJTextField.setText("");
        cpfJTextField.setText("");
        telefoneJTextField.setText("");
        especialidadeJTextField.setText("");
        crmvJTextField.setText("");
        horasTrabalhadasJTextField.setText("");
    }//GEN-LAST:event_limparJButtonActionPerformed

    private void excluirJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_excluirJButtonActionPerformed
        int id = (int) veterinarioJTable.getValueAt(veterinarioJTable.getSelectedRow(), 0);
        if (veterinarioJTable.getSelectedRow() != -1) {
            veterinariodao.deletar(id);
            JOptionPane.showMessageDialog(null, "Registro do veterinario removido.");
            lerTabela();
        } else {
            JOptionPane.showMessageDialog(null, "Selecione um veterinario para remover.");
        }
    }//GEN-LAST:event_excluirJButtonActionPerformed


