    public void lerTabela() {
        DefaultTableModel modeloPadrao = (DefaultTableModel) veterinarioJTable.getModel();
        modeloPadrao.setNumRows(0);

        for (Veterinario veterinario : veterinariodao.ler()) {
            modeloPadrao.addRow(new Object[]{
                veterinario.getId(), veterinario.getNome(), veterinario.getCpf(), veterinario.getTelefone(),
                veterinario.getEspecialidade(), veterinario.getCrmv(), veterinario.getHorasTrabalhadas()
            });
        }
    }

