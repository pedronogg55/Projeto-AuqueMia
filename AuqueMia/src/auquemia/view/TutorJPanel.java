    public void lerTabela() {
        DefaultTableModel modeloPadrao = (DefaultTableModel) tutorJTable.getModel();
        modeloPadrao.setNumRows(0);

        for (Tutor tutor : tutordao.ler()) {
            modeloPadrao.addRow(new Object[]{
                tutor.getId(), tutor.getNome(), tutor.getCpf(), tutor.getTelefone(), tutor.getEndereco()
            });
        }
    }

