    private void atualizarJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_atualizarJButtonActionPerformed
        try {
            if (tutorJTable.getSelectedRow() != -1) {
                tutor.setNome(nomeJTextField.getText());
                tutor.setCpf(cpfJTextField.getText());
                tutor.setTelefone(telefoneJTextField.getText());
                tutor.setEndereco(enderecoJTextField.getText());
                tutor.setId((int) tutorJTable.getValueAt(tutorJTable.getSelectedRow(), 0));
                tutordao.atualizar(tutor);
                JOptionPane.showMessageDialog(null, "Registro do tutor modificado com sucesso.");
                limparJButtonActionPerformed(evt);
                lerTabela();
            } else {
                JOptionPane.showMessageDialog(null, "Selecione um registro.");
            }
        } catch (RuntimeException re) {
            JOptionPane.showMessageDialog(null, re.getMessage());
            re.printStackTrace();
        }
    }//GEN-LAST:event_atualizarJButtonActionPerformed

    private void limparJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_limparJButtonActionPerformed
        nomeJTextField.setText("");
        cpfJTextField.setText("");
        telefoneJTextField.setText("");
        enderecoJTextField.setText("");
    }//GEN-LAST:event_limparJButtonActionPerformed

    private void salvarJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_salvarJButtonActionPerformed
        try {
            tutor.setNome(nomeJTextField.getText());
            tutor.setCpf(cpfJTextField.getText());
            tutor.setTelefone(telefoneJTextField.getText());
            tutor.setEndereco(enderecoJTextField.getText());
            tutordao.criar(tutor);
            JOptionPane.showMessageDialog(null, "Um registro do tutor foi salvo com sucesso.");
            limparJButtonActionPerformed(evt);
            lerTabela();
        } catch (RuntimeException re) {
            JOptionPane.showMessageDialog(null, re.getMessage());
            re.printStackTrace();
        }
    }//GEN-LAST:event_salvarJButtonActionPerformed

    private void excluirJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_excluirJButtonActionPerformed
        int id = (int) tutorJTable.getValueAt(tutorJTable.getSelectedRow(), 0);
        if (tutorJTable.getSelectedRow() != -1) {
            tutordao.deletar(id);
            JOptionPane.showMessageDialog(null, "Registro do tutor removido.");
            lerTabela();
        } else {
            JOptionPane.showMessageDialog(null, "Selecione um tutor para remover.");
        }
    }//GEN-LAST:event_excluirJButtonActionPerformed
    

